/**
 * A deliberately naive serialiser, kept as a comparison target.
 *
 * This is not dead code: it is the baseline the compact serialiser is measured against, and the
 * test that asserts "our output is measurably smaller" needs a specific, stable thing to be smaller
 * than. It is written the way an export pipeline looks when nobody has thought about output size —
 * an XML declaration, a commented banner, an `xlink` namespace nothing uses, a `<g>` per shape with
 * an identity transform, inline `style` attributes listing every property including the defaults,
 * six decimal places and indentation.
 *
 * It must always describe the *same artwork* as the compact serialiser. The comparison test parses
 * both outputs and asserts the geometry matches, so it can never pass by dropping content.
 */

import { toVerbosePathData } from '../vector/path-data';
import type { SvgArtwork } from './artwork';

const NAIVE_INDENT = '    ';

function naiveStyleAttribute(shape: SvgArtwork['shapes'][number]): string {
  const { style } = shape;
  const declarations = [
    `fill:${style.fill ?? 'none'}`,
    `fill-opacity:${style.fillOpacity.toFixed(6)}`,
    `fill-rule:${style.fillRule}`,
    style.stroke === null ? 'stroke:none' : `stroke:${style.stroke}`,
    `stroke-width:${style.strokeWidth.toFixed(6)}`,
    `stroke-linecap:${style.lineCap}`,
    `stroke-linejoin:${style.lineJoin}`,
    `stroke-opacity:${style.strokeOpacity.toFixed(6)}`,
    style.dashArray.length === 0
      ? 'stroke-dasharray:none'
      : `stroke-dasharray:${style.dashArray.map((entry) => entry.toFixed(6)).join(',')}`,
    `opacity:${shape.opacity.toFixed(6)}`,
  ];
  return declarations.join(';');
}

/** The verbose counterpart of `serializeSvg`. Same artwork, much larger file. */
export function serializeNaiveSvg(artwork: SvgArtwork): string {
  const { minX, minY, maxX, maxY } = artwork.viewBox;
  const lines: string[] = [];
  lines.push('<?xml version="1.0" encoding="UTF-8" standalone="no"?>');
  lines.push('<!-- Generated by Euler\'s Forge (naive comparison serialiser) -->');
  lines.push(
    `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" version="1.1" ` +
      `width="${artwork.width.toFixed(6)}px" height="${artwork.height.toFixed(6)}px" ` +
      `viewBox="${minX.toFixed(6)} ${minY.toFixed(6)} ${(maxX - minX).toFixed(6)} ${(maxY - minY).toFixed(6)}">`,
  );
  lines.push(`${NAIVE_INDENT}<defs id="defs1" />`);
  lines.push(`${NAIVE_INDENT}<metadata id="metadata1">Euler's Forge document export</metadata>`);

  if (artwork.background !== null && artwork.background !== undefined) {
    lines.push(`${NAIVE_INDENT}<g id="background" transform="translate(0.000000,0.000000)">`);
    lines.push(
      `${NAIVE_INDENT}${NAIVE_INDENT}<rect x="${minX.toFixed(6)}" y="${minY.toFixed(6)}" ` +
        `width="${(maxX - minX).toFixed(6)}" height="${(maxY - minY).toFixed(6)}" ` +
        `style="fill:${artwork.background};fill-opacity:1.000000;fill-rule:nonzero;stroke:none;stroke-width:1.000000;stroke-linecap:butt;stroke-linejoin:miter;stroke-opacity:1.000000;stroke-dasharray:none;opacity:1.000000" />`,
    );
    lines.push(`${NAIVE_INDENT}</g>`);
  }

  artwork.shapes.forEach((shape, index) => {
    lines.push(`${NAIVE_INDENT}<g id="layer-${String(index + 1)}" transform="translate(0.000000,0.000000)">`);
    if (shape.name.length > 0) {
      lines.push(`${NAIVE_INDENT}${NAIVE_INDENT}<title>${shape.name}</title>`);
    }
    lines.push(
      `${NAIVE_INDENT}${NAIVE_INDENT}<path class="artwork-shape" d="${toVerbosePathData(shape.path)}" style="${naiveStyleAttribute(shape)}" />`,
    );
    lines.push(`${NAIVE_INDENT}</g>`);
  });

  lines.push('</svg>');
  return lines.join('\n');
}
